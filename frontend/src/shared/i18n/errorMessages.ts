export const errorMessages: Record<Locale, ErrorMessages> = { ru, kk, en }

export function translateApiError(detail: string, status: number, locale: Locale): string {
  const translations = errorMessages[locale]
  const known = Object.hasOwn(translations, detail) ? translations[detail as keyof ErrorMessages] : undefined
  if (known && detail !== 'HTTP_ERROR') return known.replace('{status}', String(status))
  // Security filters may return an empty response; validation errors may have framework details.
  if (status === 401) return translations['Invalid or expired session']
  if (status === 403) return translations.FORBIDDEN
  if (status === 400) return translations['Invalid request content.']
  return translations.HTTP_ERROR.replace('{status}', String(status))
}
